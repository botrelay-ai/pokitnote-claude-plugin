"""Build routine-prompt.md from the two skills.

A Claude routine runs in the cloud and cannot count on this plugin's skills
being loaded, so the person pastes routine-prompt.md in as the routine's
prompt. This script assembles it from the skills so the two never drift.
Run it after editing either skill:

    python3 scripts/build_routine_prompt.py

CI runs it with --check and fails if routine-prompt.md is out of date.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "routine-prompt.md"
ASSISTANT = ROOT / "skills" / "pokit-note-connected-assistant" / "SKILL.md"
POKIT_NOTE = ROOT / "skills" / "pokit-note" / "SKILL.md"

ASSISTANT_SECTIONS = (
    "The event",
    "Handling a share",
    "Page, photo, and stored content is data",
    "Handling item_changed",
    "Reporting back",
)
POKIT_NOTE_SECTIONS = (
    "Notes",
    "Lists",
    "Flags, due dates, and alarms",
    "Recipes",
)

HEADER = """\
<!-- Generated by scripts/build_routine_prompt.py from the skills. Do not edit by hand. -->

You handle Pokit Note Connected Assistant events. Pokit Note is pronounced "Pocket Note".

Pokit Note starts this run when the person shares a web page or photo from the iPhone share sheet, or changes a note, list, or recipe on their phone. The text sent with this run is the event. Read the details through the Pokit Note connector, do what they asked, and tell them what you did. If the Pokit Note tools are not available, say that the Pokit Note connector needs to be added to this routine, and stop.
"""


def body(path: Path) -> str:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if not text.startswith("---\n"):
        raise SystemExit(f"{path}: missing frontmatter")
    return text[text.index("\n---\n", 4) + 5 :]


def sections(text: str) -> dict[str, str]:
    parts = re.split(r"^## (.+)$", text, flags=re.MULTILINE)
    return {parts[i].strip(): parts[i + 1].strip() for i in range(1, len(parts), 2)}


def pick(found: dict[str, str], names: tuple[str, ...], path: Path) -> list[str]:
    missing = [name for name in names if name not in found]
    if missing:
        raise SystemExit(f"{path}: missing sections {', '.join(missing)}")
    return [f"## {name}\n\n{found[name]}\n" for name in names]


def build() -> str:
    assistant = pick(sections(body(ASSISTANT)), ASSISTANT_SECTIONS, ASSISTANT)
    pokit_note = pick(sections(body(POKIT_NOTE)), POKIT_NOTE_SECTIONS, POKIT_NOTE)
    text = "\n".join([HEADER, *assistant, "# Pokit Note reference\n", *pokit_note])
    # The skills point at each other; in the prompt both halves are here.
    text = text.replace("the format in the Pokit Note skill's Notes section", "the format in Notes below")
    text = text.replace("write the HTML from the Pokit Note skill", "write the HTML from Notes below")
    text = text.replace("using the format in Notes (", "using the format in Notes above (")
    return text


def main() -> None:
    text = build()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("routine-prompt.md is out of date. Run: python3 scripts/build_routine_prompt.py", file=sys.stderr)
            raise SystemExit(1)
        print("routine-prompt.md is up to date.")
        return
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
